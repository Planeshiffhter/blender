"""Make a real animated Blender continuation (not an FFmpeg shot montage).

Input: existing, artist-approved 20-second A_Second_Taj.blend and the improved
second-episode Kokoro WAV + audio/timing.json.

Output: a NEW 40-second editable .blend containing new camera cuts at the new
speaker boundaries, 480 new frames of speech shape-key animation, and audio
starting at frame 481. The original 480 frames are left in place.

Usage from the repository's episode directory:
  blender --background A_Second_Taj.blend --python extension_review/extend_blender.py

Rendering and publishing an MP4 MUST be a separate, reviewed step. No video is
generated by this script; its job is to produce the editable 40-second scene.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import bpy
from mathutils import Vector

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / "extension_review"
SECOND = ROOT / "next_20_seconds"
FPS = 24
FIRST_FRAME = 481
LAST_FRAME = 960
OUTPUT = EXT / "A_Second_Taj_40s_Review.blend"
SPEAKER_SAMPLES = {
    "Tara": [2.5, 8.0, 15.1],
    "Maya": [5.1, 12.1, 18.0],
}


def duration_checks(timing: dict) -> None:
    if timing.get("fps") != FPS or timing.get("duration") != 20:
        raise RuntimeError("Expected exactly 20 seconds at 24 frames per second")
    if len(timing.get("lines", [])) != 6:
        raise RuntimeError("Expected six new speech lines")
    previous_end = 0.0
    for i, line in enumerate(timing["lines"]):
        who = "Tara" if i % 2 == 0 else "Maya"
        if line.get("speaker") != who:
            raise RuntimeError(f"Dialogue #{i+1} must be from {who}")
        start, end = float(line["start"]), float(line["end"])
        if not 0 <= previous_end <= start < end <= 20:
            raise RuntimeError(f"Overlapping or out-of-bounds dialogue #{i+1}")
        previous_end = end
    for name in ("Tara", "Maya"):
        arr = timing.get("mouth", {}).get(name)
        if not isinstance(arr, list) or len(arr) != 480:
            raise RuntimeError(f"Expected 480 mouth samples for {name}")
        if any(not isinstance(v, (int, float)) or not math.isfinite(v) or not 0 <= v <= 1 for v in arr):
            raise RuntimeError(f"Invalid mouth curve for {name}")


def speaker_mouth(name: str):
    """Use the original face/mouth mesh, not a substitute cartoon."""
    obj = bpy.data.objects.get(name + " • mouth")
    if obj is None or obj.data is None or obj.data.shape_keys is None:
        raise RuntimeError(f"Missing original animated character: {name} • mouth")
    key = obj.data.shape_keys.key_blocks.get("Speech")
    if key is None:
        raise RuntimeError(f"Missing Speech shape key on {name}")
    return obj, key


def append_lip_sync(name: str, values: list[float]) -> None:
    _, key = speaker_mouth(name)
    # Inserting new keys into the EXISTING action preserves the old frames.
    # Start from zero so an end-frame hold does not leak into the new scene.
    key.value = 0
    key.keyframe_insert(data_path="value", frame=480)
    key.keyframe_insert(data_path="value", frame=FIRST_FRAME)
    for i, value in enumerate(values):
        key.value = float(value)
        key.keyframe_insert(data_path="value", frame=FIRST_FRAME + i)
    if key.id_data.animation_data is not None and key.id_data.animation_data.action is not None:
        action = key.id_data.animation_data.action
        # Blender 4.x traditional actions support fcurves, as the original
        # update_blend.py script expects. Do not discard the source action.
        for fcurve in getattr(action, "fcurves", []):
            for point in fcurve.keyframe_points:
                if point.co.x >= 480:
                    point.interpolation = "LINEAR"


def append_sound() -> None:
    file_path = SECOND / "audio" / "Conversation.wav"
    if not file_path.is_file():
        raise RuntimeError(f"Missing generated continuation audio: {file_path}")
    scene = bpy.context.scene
    editor = scene.sequence_editor_create()
    strips = editor.sequences if hasattr(editor, "sequences") else editor.strips
    # Remove only previous attempts at the continuation; keep original audio.
    for strip in list(strips):
        if strip.type == "SOUND" and strip.name.startswith("Tara and Maya Part Two"):
            strips.remove(strip)
    new_strip = strips.new_sound("Tara and Maya Part Two • Bella", str(file_path.resolve()), 2, FIRST_FRAME)
    new_strip.sound.pack()
    new_strip.frame_final_duration = 480


def append_cameras(timing: dict) -> None:
    scene = bpy.context.scene
    if scene.camera is None:
        raise RuntimeError("The source 20-second scene has no camera")
    main_camera = scene.camera
    count = {"Tara": 0, "Maya": 0}
    new_collection = bpy.data.collections.get("Episode 2 | new 3D camera shots")
    if new_collection is None:
        new_collection = bpy.data.collections.new("Episode 2 | new 3D camera shots")
        scene.collection.children.link(new_collection)

    for i, line in enumerate(timing["lines"]):
        speaker = line["speaker"]
        sample_at = SPEAKER_SAMPLES[speaker][count[speaker]]
        count[speaker] += 1
        scene.frame_set(max(1, min(480, round(sample_at * FPS))))
        # Read an ORIGINAL well-composed, speaker-specific camera position.
        # This copies a 3D camera transform, NOT any rendered video frames.
        source_cam = scene.camera or main_camera
        camera = bpy.data.objects.new(f"Part 2 Shot {i+1} | {speaker}", source_cam.data.copy())
        new_collection.objects.link(camera)
        camera.matrix_world = source_cam.matrix_world.copy()
        camera.rotation_mode = "QUATERNION"

        # Preserve framing direction from the original 3D shot, with a small
        # animated dolly to avoid the frozen-clip look of the rejected montage.
        origin = camera.matrix_world.translation.copy()
        forward = camera.matrix_world.to_quaternion() @ Vector((0.0, 0.0, -1.0))
        if forward.length == 0:
            raise RuntimeError("Invalid camera orientation")
        advance = forward.normalized() * max(0.02, min(0.16, camera.data.lens / 700))
        shot_start = FIRST_FRAME if i == 0 else max(
            FIRST_FRAME,
            FIRST_FRAME + round((float(line["start"]) - 0.12) * FPS),
        )
        shot_end = (
            LAST_FRAME if i == len(timing["lines"]) - 1
            else FIRST_FRAME + round((float(timing["lines"][i+1]["start"]) - 0.12) * FPS) - 1
        )
        camera.location = origin
        camera.keyframe_insert(data_path="location", frame=shot_start)
        camera.location = origin + advance
        camera.keyframe_insert(data_path="location", frame=shot_end)
        # Each new scene cut follows the speaker, not arbitrary source footage.
        marker = scene.timeline_markers.new(f"Part 2 | {speaker} line {i+1}", frame=shot_start)
        marker.camera = camera

    scene.camera = main_camera  # Leave the original camera configuration intact.
    scene.frame_set(FIRST_FRAME)


def read_srt(text: str):
    """A minimal SRT reader preserving the first episode's caption text."""
    import re
    for block in re.split(r"\n\s*\n", text.strip()):
        rows = block.splitlines()
        if rows[0].strip().isdigit():
            rows = rows[1:]
        left, right = rows[0].split(" --> ")
        yield left, right, "\n".join(rows[1:])


def parse_srt_time(text: str) -> float:
    hours, minutes, remainder = text.split(":")
    seconds, millis = remainder.split(",")
    return int(hours) * 3600 + int(minutes) * 60 + int(seconds) + int(millis) / 1000


def srt_time(seconds: float) -> str:
    total = round(seconds * 1000)
    h, total = divmod(total, 3_600_000)
    m, total = divmod(total, 60_000)
    s, ms = divmod(total, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def write_40s_subtitles(timing: dict) -> None:
    # Keep original 0-20s captions exactly; only offset new lines by +20s.
    cues = list(read_srt((ROOT / "English.srt").read_text(encoding="utf-8")))
    captions = [(parse_srt_time(a), parse_srt_time(b), text) for a, b, text in cues]
    for line in timing["lines"]:
        a = float(line["start"]) + 20
        b = min(40, float(line["end"]) + 20 + 0.07)
        captions.append((a, b, line["text"]))
    (EXT / "English_40s.srt").write_text(
        "\n\n".join(
            f"{i}\n{srt_time(a)} --> {srt_time(b)}\n{text}"
            for i, (a, b, text) in enumerate(captions, start=1)
        ) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    timing = json.loads((SECOND / "audio" / "timing.json").read_text(encoding="utf-8"))
    duration_checks(timing)
    scene = bpy.context.scene
    if scene.frame_end != 480:
        raise RuntimeError(
            f"The unchanged source must be the original 480-frame scene (got {scene.frame_end})"
        )
    if scene.render.fps != FPS:
        raise RuntimeError(f"Expected original 24 fps, found {scene.render.fps}")
    for name in ("Tara", "Maya"):
        append_lip_sync(name, timing["mouth"][name])
    append_sound()
    append_cameras(timing)
    scene.frame_end = LAST_FRAME
    scene.frame_set(1)
    write_40s_subtitles(timing)
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.wm.save_as_mainfile(filepath=str(OUTPUT.resolve()), compress=True)
    print("CREATED real 960-frame 3D scene:", OUTPUT)
    print("Subtitle timing:", EXT / "English_40s.srt")
    print("IMPORTANT: A new 3D render and visual/audio review are required before publishing.")


if __name__ == "__main__":
    main()
